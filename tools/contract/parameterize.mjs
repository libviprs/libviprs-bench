// --- CLI --------------------------------------------------------------------

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const argv = process.argv.slice(2);
  const mode = argv.includes('--write') ? 'write' : argv.includes('--check') ? 'check' : null;
  if (!mode) {
    console.error('usage: parameterize.mjs (--check | --write)');
    process.exit(EXIT.USAGE);
  }

  const rev = readFileSync(REV_FILE, 'utf8').trim();
  const src = readFileSync(FROZEN, 'utf8');
  let result;
  try {
    result = parameterize(src);
  } catch (err) {
    if (err instanceof AnchorMoved) {
      console.error(`parameterize: refused, ${err.message}`);
      process.exit(EXIT.REFUSED);
    }
    throw err;
  }

  const banner =
    `/* GENERATED from tools/contract/upstream/dashboard.js (causl-org @ ${rev})\n` +
    `   by tools/contract/parameterize.mjs. Do not edit: change config.json, or\n` +
    `   the parameteriser, and re-run \`parameterize.mjs --write\`.\n` +
    `   Edits applied: ${result.applied.join(', ')} */\n`;
  const next = banner + result.out;

  if (mode === 'write') {
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(OUT, next);
    console.log(`parameterize: wrote ${OUT} (${result.applied.length} edits)`);
    process.exit(EXIT.OK);
  }

  if (!existsSync(OUT)) {
    console.error(`parameterize: STALE, ${OUT} does not exist. Run --write.`);
    process.exit(EXIT.STALE);
  }
  if (readFileSync(OUT, 'utf8') !== next) {
    console.error(`parameterize: STALE, ${OUT} is not what the frozen file and this script produce.`);
    console.error('              Run --write. Do not hand-edit generated/.');
    process.exit(EXIT.STALE);
  }
  console.log(`parameterize: generated/dashboard.js is current (${result.applied.length} edits)`);
  process.exit(EXIT.OK);
}
