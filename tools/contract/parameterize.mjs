// Anchored edits
// ---------------------------------------------------------------------------

/** A constant whose initializer is a bracketed literal: anchor on the exact
 *  declaration prefix, then take the balanced literal that follows and wrap it.
 *  Comments inside the literal (LIBRARY_COLOR has one per line) survive, which
 *  is the point of wrapping rather than rewriting. */
const wrap = (id, open, path) => ({ kind: 'wrap', id, open, path });
/** A constant whose initializer is a scalar running to end of line. */
const scalar = (id, open, path) => ({ kind: 'scalar', id, open, path });
/** An exact string swap. */
const swap = (id, find, replace) => ({ kind: 'swap', id, find, replace });

const EDITS = [
  swap(
    'preamble',
    "(() => {\n  'use strict'\n",
    `(() => {\n  'use strict'\n\n${PREAMBLE}`,
  ),

  wrap('LIBRARY_ORDER', '  const LIBRARY_ORDER = ', 'series.order'),
  wrap('LIBRARY_LABEL', '  const LIBRARY_LABEL = ', 'series.label'),
  wrap('LIBRARY_ANNOTATION', '  const LIBRARY_ANNOTATION = ', 'series.annotation'),
  wrap('LIBRARY_COLOR', '  const LIBRARY_COLOR = ', 'series.color'),
  wrap('LIBRARY_DASH', '  const LIBRARY_DASH = ', 'series.dash'),
  wrap('DEFAULT_LIBRARIES', '  const DEFAULT_LIBRARIES = new Set(', 'defaults.libraries'),
  wrap('DEFAULT_SCALES', '  const DEFAULT_SCALES = new Set(', 'defaults.scales'),
  wrap('VERDICT_COLOR', '  const VERDICT_COLOR = ', 'verdict.color'),

  scalar('REGRESSION_PCT', '  const REGRESSION_PCT = ', 'verdict.regressionPct'),
  scalar('IMPROVED_PCT', '  const IMPROVED_PCT = ', 'verdict.improvedPct'),
  scalar('PASS_PCT', '  const PASS_PCT = ', 'verdict.passPct'),
  scalar('NOISY_PROXY', '  const NOISY_PROXY = ', 'verdict.noisyProxy'),

  // The gate behaviour. After the non-finite check, because "measured, not
  // gated" is a lie about a cell whose median is not a number.
  swap(
    'gate-check',
    `    const last = points[points.length - 1]
    if (!Number.isFinite(last.medianMs)) {
      return { kind: 'unknown', detail: 'last median is non-finite' }
    }
`,
    `    const last = points[points.length - 1]
    if (!Number.isFinite(last.medianMs)) {
      return { kind: 'unknown', detail: 'last median is non-finite' }
    }

    // libviprs (config-gated, inert upstream): a cell that was measured but
    // not gated gets no verdict at all.
    const __ungated = __gateVerdict(last)
    if (__ungated) return __ungated
`,
  ),

  // The noise behaviour, ahead of the regression and improvement lines: a
  // metric whose replicate spread is 53.3% clears a 10% threshold from nothing.
  swap(
    'noise-check',
    `    if (delta > REGRESSION_PCT) return { kind: 'regressed', detail }`,
    `    // libviprs (config-gated, inert upstream): a delta inside this cell's
    // own replicate spread is noise, and it is decided before the thresholds
    // below because those thresholds cannot tell one from a real move.
    const __noise = __noiseVerdict(last, delta, detail)
    if (__noise) return __noise

    if (delta > REGRESSION_PCT) return { kind: 'regressed', detail }`,
  ),

  // The chart point's shape. Without this the verdict rules read fields that
  // `groupSections` never copied out of the sample, which looks exactly like a
  // rule that is off.
  swap(
    'carry-fields',
    `          boundaryCrossings: sample.boundaryCrossings,
          boundaryBytes: sample.boundaryBytes,
        })`,
    `          boundaryCrossings: sample.boundaryCrossings,
          boundaryBytes: sample.boundaryBytes,
          // libviprs (config-gated, inert upstream): the fields the verdict
          // rules read live on the sample, and this object is the only thing
          // computeVerdict ever sees.
          ...__carryFields(sample),
        })`,
  ),

  // The legend's verdict slot.
  swap(
    'verdict-chip',
    `        \`<span class="bench-legend-verdict" title="\${escapeHtml(verdict.detail)}">\` +
        \`<span class="bench-legend-verdict-dot" aria-hidden="true"></span>\` +
        \`<span class="bench-legend-verdict-label">\${verdict.kind}</span>\` +
        \`</span>\` +`,
    `        __verdictChip(verdict) +`,
  ),

  // The era axes.
  swap(
    'era-axes',
    `    const libsOf = (e) => {
      const set = new Set()
      for (const smp of e.samples ?? []) if (smp.library) set.add(smp.library)
      return set
    }
    const sameLibs = (a, b) => a.size === b.size && [...a].every((l) => b.has(l))
    // Walk back from the newest run while the library set is unchanged.
    const latest = libsOf(history[history.length - 1])
    if (latest.size === 0) return 0
    let start = history.length - 1
    while (start > 0) {
      const prev = history[start - 1]
      // Entries with no samples at all carry no library claim; step
      // over them rather than letting one end the era.
      const prevLibs = libsOf(prev)
      if (prevLibs.size > 0 && !sameLibs(prevLibs, latest)) break
      start -= 1
    }
    return start`,
    `    // Walk back from the newest run while the era signature is unchanged.
    // With the default single library-set axis this is upstream's comparison
    // exactly; libviprs adds the host fingerprint and the filesystem type so a
    // run on a different machine starts a new era.
    const latest = __eraSignature(history[history.length - 1])
    if (latest === null) return 0
    let start = history.length - 1
    while (start > 0) {
      // Entries carrying no claim on any axis step over rather than ending
      // the era, which is what an empty \`samples\` did upstream.
      const prev = __eraSignature(history[start - 1])
      if (prev !== null && prev !== latest) break
      start -= 1
    }
    return start`,
  ),
];

