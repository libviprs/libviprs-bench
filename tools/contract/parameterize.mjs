class AnchorMoved extends Error {}

function countOf(hay, needle) {
  let n = 0;
  let i = hay.indexOf(needle);
  while (i !== -1) {
    n += 1;
    i = hay.indexOf(needle, i + needle.length);
  }
  return n;
}

/** Span of the bracketed literal starting at `from`, skipping strings, template
 *  literals, regexes-by-proxy and comments. Returns the index one past its
 *  closing bracket. */
export function balancedEnd(src, from) {
  const open = src[from];
  const close = { '{': '}', '[': ']', '(': ')' }[open];
  if (!close) throw new AnchorMoved(`expected a bracketed literal at offset ${from}, found ${JSON.stringify(open)}`);
  let depth = 0;
  for (let i = from; i < src.length; i += 1) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') {
      i = src.indexOf('\n', i);
      if (i === -1) break;
      continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      i = src.indexOf('*/', i) + 1;
      continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      const q = c;
      i += 1;
      while (i < src.length && src[i] !== q) {
        if (src[i] === '\\') i += 1;
        i += 1;
      }
      continue;
    }
    if (c === open) depth += 1;
    else if (c === close) {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
  }
  throw new AnchorMoved(`unbalanced ${open} starting at offset ${from}`);
}

export function parameterize(src) {
  let out = src;
  const applied = [];
  for (const edit of EDITS) {
    if (edit.kind === 'swap') {
      const n = countOf(out, edit.find);
      if (n !== 1) {
        throw new AnchorMoved(
          `edit "${edit.id}": its anchor matches ${n} times in dashboard.js, not once. ` +
            'Upstream moved; re-pin and re-anchor rather than patching the wrong place.',
        );
      }
      out = out.replace(edit.find, () => edit.replace);
      applied.push(edit.id);
      continue;
    }

    const n = countOf(out, edit.open);
    if (n !== 1) {
      throw new AnchorMoved(
        `edit "${edit.id}": the declaration ${JSON.stringify(edit.open)} matches ${n} times, not once`,
      );
    }
    const at = out.indexOf(edit.open) + edit.open.length;
    let end;
    if (edit.kind === 'wrap') {
      end = balancedEnd(out, at);
    } else {
      const nl = out.indexOf('\n', at);
      const cm = out.indexOf('//', at);
      end = cm !== -1 && cm < nl ? cm : nl;
      while (end > at && out[end - 1] === ' ') end -= 1;
    }
    const literal = out.slice(at, end);
    out = `${out.slice(0, at)}__cfg('${edit.path}', ${literal})${out.slice(end)}`;
    applied.push(edit.id);
  }
  return { out, applied };
}

