#!/usr/bin/env node
// Turn the frozen dashboard into a config-driven one, without editing the
// frozen file.
//
//   node tools/contract/parameterize.mjs --write    regenerate generated/
//   node tools/contract/parameterize.mjs --check    fail if generated/ is stale
//
// Every edit below is ANCHORED on an exact string from `upstream/dashboard.js`
// and must match exactly once. If upstream changes that string, this refuses
// rather than patching the wrong place, which is the difference between a
// vendored copy and the port in `tools/charts/chart.mjs` that quietly diverged.
// `sync-contract.sh --check` catches the same drift one step earlier; this is
// the second line.
//
// Each edit replaces a hard-coded literal with `__cfg('<path>', <the same
// literal>)`. With no config present every read returns the literal, so the
// generated file behaves exactly as the frozen one does. `golden-render.test.mjs`
// proves that by rendering both and comparing the HTML byte for byte, and that
// is the property that makes this parameterisation safe to offer upstream: it
// changes nothing about causl's own page.
//
// Config reaches the browser as a synchronous global, set by a `<script>` before
// this file loads:
//
//   <script>window.LIBVIPRS_BENCH_CONFIG = { ... }</script>
//   <script src="./dashboard.js"></script>
//
// Synchronous because the constants are evaluated the moment the IIFE runs, so
// there is no await to hang a fetch on, and a page that renders causl's defaults
// for 200ms and then swaps them is worse than one that never had them.
//
// Exit codes: 0 ok · 1 stale (--check) · 2 usage · 3 refused (an anchor moved)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const FROZEN = join(here, 'upstream', 'dashboard.js');
const OUT_DIR = join(here, 'generated');
const OUT = join(OUT_DIR, 'dashboard.js');
const REV_FILE = join(here, 'UPSTREAM_REV');

const EXIT = { OK: 0, STALE: 1, USAGE: 2, REFUSED: 3 };

// ---------------------------------------------------------------------------
// The preamble. Self-contained: a flat static site loads this as one <script>,
// so it can import nothing.
// ---------------------------------------------------------------------------

const PREAMBLE_BEGIN = '  /* ==== libviprs contract preamble: BEGIN (generated, not upstream) ==== */';
const PREAMBLE_END = '  /* ==== libviprs contract preamble: END ==== */';

const PREAMBLE = `${PREAMBLE_BEGIN}
  /* Generated by tools/contract/parameterize.mjs from tools/contract/upstream/
     dashboard.js. Do not edit this file: edit config.json, or the parameteriser.

     Every constant below this block reads through __cfg(path, literal). The
     literal is causl's, unchanged, so with no config present this file is
     behaviourally identical to the frozen one. */

  const __CONFIG =
    (typeof globalThis !== 'undefined' && globalThis.LIBVIPRS_BENCH_CONFIG) || null

  /** One dotted path out of the config, or the upstream literal. Objects and
   *  arrays REPLACE the literal rather than merging into it: a merge would
   *  leave causl's series ids sitting in libviprs's plot order, which is the
   *  shape of bug that is hardest to see on a page that still renders. */
  function __cfg(path, fallback) {
    if (__CONFIG === null || typeof __CONFIG !== 'object') return fallback
    let node = __CONFIG
    for (const seg of path.split('.')) {
      if (node === null || typeof node !== 'object' || !(seg in node)) return fallback
      node = node[seg]
    }
    return node === null || node === undefined ? fallback : node
  }

  /** A sample that says it was measured but not gated gets no verdict. A
   *  verdict chip is a claim that a threshold ruled on the number, and when
   *  nothing gated the cell no threshold did. Only the literal \`false\` counts:
   *  absent or null means nobody said, which is a different fact.
   *
   *  Off unless config turns it on, and off is upstream's behaviour exactly. */
  function __gateVerdict(sample) {
    if (!__cfg('verdict.gate.enabled', false)) return null
    const field = __cfg('verdict.gate.field', 'gated')
    if (!sample || sample[field] !== false) return null
    return {
      kind: __cfg('verdict.gate.kind', 'ungated'),
      detail: __cfg('verdict.gate.label', 'measured, not gated'),
    }
  }

  /** A delta smaller than this cell's own replicate spread is noise: not a
   *  pass, not a regression, not an improvement. The first full libviprs
   *  capture measured a median replicate spread of 3.46% across 48 metrics
   *  with one metric at 53.3%, so a 20% delta on that metric is what an idle
   *  machine produces, and ruling it a regression invents a result.
   *
   *  A sample carrying no measured spread does not fall through to the
   *  thresholds by default: \`onMissingSpread: 'unknown'\` refuses to rule,
   *  because a spread that was not measured is not a spread. \`'skip'\` is the
   *  upstream behaviour, and upstream is the default.
   *
   *  \`spread\` is a PERCENT (3.46 means 3.46%); \`delta\` is a fraction. */
  function __noiseVerdict(sample, delta, detail) {
    if (!__cfg('verdict.noise.enabled', false)) return null
    const field = __cfg('verdict.noise.spreadField', 'replicateSpreadPct')
    const raw = sample ? sample[field] : null
    const kind = __cfg('verdict.noise.kind', 'noise')
    if (!Number.isFinite(raw)) {
      if (__cfg('verdict.noise.onMissingSpread', 'skip') === 'unknown') {
        return {
          kind: 'unknown',
          detail:
            detail +
            ', and this cell carries no measured replicate spread, so there is nothing to ' +
            'tell a real move from noise',
        }
      }
      return null
    }
    const floor = __cfg('verdict.noise.floorPct', null)
    const spreadPct = Number.isFinite(floor) ? Math.max(raw, floor) : raw
    if (Math.abs(delta) * 100 > spreadPct) return null
    return {
      kind,
      detail: detail + ', inside this cell\\'s ' + formatNumber(spreadPct) + '% replicate spread',
    }
  }

  /** The legend's verdict slot. Kinds listed in \`verdict.noChipKinds\` render
   *  their label as plain text instead of a chip, because a chip is the page's
   *  way of saying a threshold ruled. Empty upstream, so upstream gets exactly
   *  the chip it has always emitted, character for character. */
  function __verdictChip(verdict) {
    const noChip = __cfg('verdict.noChipKinds', [])
    if (Array.isArray(noChip) && noChip.includes(verdict.kind)) {
      return (
        \`<span class="bench-legend-measured" title="\${escapeHtml(verdict.detail)}">\` +
        \`<span class="bench-legend-measured-label">\${escapeHtml(verdict.detail)}</span>\` +
        \`</span>\`
      )
    }
    return (
      \`<span class="bench-legend-verdict" title="\${escapeHtml(verdict.detail)}">\` +
      \`<span class="bench-legend-verdict-dot" aria-hidden="true"></span>\` +
      \`<span class="bench-legend-verdict-label">\${verdict.kind}</span>\` +
      \`</span>\`
    )
  }

  /** The fields a chart point carries out of its sample.
   *
   *  \`groupSections\` builds a fixed-shape point object and that object is the
   *  ONLY thing \`computeVerdict\` ever sees, so a rule that reads a sample field
   *  reads nothing unless the field is carried across here. With no config the
   *  list is empty and the spread adds nothing, so upstream's point object is
   *  unchanged down to its key order.
   *
   *  The two verdict rules add their own field automatically when they are on,
   *  because a rule that silently reads undefined is worse than one that is
   *  off. \`samples.carry\` is for everything else the page wants to keep, such
   *  as a metric's unit and direction. */
  function __carryFields(sample) {
    const extra = __cfg('samples.carry', [])
    const wanted = Array.isArray(extra) ? [...extra] : []
    if (__cfg('verdict.noise.enabled', false)) {
      wanted.push(__cfg('verdict.noise.spreadField', 'replicateSpreadPct'))
    }
    if (__cfg('verdict.gate.enabled', false)) {
      wanted.push(__cfg('verdict.gate.field', 'gated'))
    }
    if (wanted.length === 0) return {}
    const out = {}
    for (const f of wanted) if (f in sample) out[f] = sample[f]
    return out
  }

  /** What makes two runs the same era, as a comparable string, or null when the
   *  entry carries no claim at all.
   *
   *  Upstream breaks an era on the measured library set and nothing else, which
   *  is right when every run comes off one CI machine. libviprs runs are taken
   *  on whatever host is to hand, so the host fingerprint and the filesystem
   *  type are axes too: otherwise a run on a different machine draws a line
   *  across two machines and the step between them reads as a regression.
   *
   *  With the default single library-set axis this returns null for an entry
   *  with no samples and a sorted id list otherwise, which is exactly what
   *  upstream's libsOf/sameLibs pair decided. */
  function __eraSignature(entry) {
    const axes = __cfg('era.axes', [{ id: 'series', from: 'samples[].library', kind: 'set' }])
    const pluck = (node, path) => {
      let nodes = [node]
      for (const raw of path.split('.')) {
        const splat = raw.endsWith('[]')
        const seg = splat ? raw.slice(0, -2) : raw
        const next = []
        for (const n of nodes) {
          if (n === null || typeof n !== 'object') continue
          const v = n[seg]
          if (v === undefined || v === null) continue
          if (splat) {
            if (Array.isArray(v)) next.push(...v)
          } else {
            next.push(v)
          }
        }
        nodes = next
      }
      return nodes
    }
    const parts = []
    let anyClaim = false
    for (const axis of axes) {
      const vals = pluck(entry, axis.from)
      if (vals.length > 0) anyClaim = true
      const shown =
        axis.kind === 'set'
          ? [...new Set(vals.map(String))].sort()
          : vals.map(String)
      parts.push(axis.id + '=' + shown.join('\\u0001'))
    }
    return anyClaim ? parts.join('\\u0002') : null
  }
${PREAMBLE_END}
`;

